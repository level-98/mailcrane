#!/usr/bin/env python3
"""Generate the Android brand theme from colors.json and check its contrast."""

import argparse
import json
import sys
from pathlib import Path


ROOT = Path(__file__).resolve().parent.parent
DESIGN = ROOT / "design"
COLORS_PATH = DESIGN / "colors.json"
ANDROID_PATH = ROOT / "android/app/src/main/java/app/mailcrane/ui/theme/BrandColors.kt"

HEADER = "// generated by design/gen_theme.py, don't edit\n"

ROLES = [
    ("Primary", "primary", "primary"),
    ("OnPrimary", "fixed-white", "dark.surface"),
    ("PrimaryContainer", "primaryContainer", "primaryDark"),
    ("OnPrimaryContainer", "primaryDark", "primaryContainer"),
    ("Surface", "surface", "dark.surface"),
    ("SurfaceDim", "surfaceDim", "dark.surfaceHigh"),
    ("SurfaceHigh", "surfaceDim", "dark.surfaceHigh"),
    ("SurfaceHighest", "surfaceHighest", "dark.surfaceHighest"),
    ("Ink", "ink", "dark.ink"),
    ("InkMuted", "inkMuted", "dark.inkMuted"),
    # Component boundaries (off switches, outlined fields and buttons): 3:1 (#395).
    ("Outline", "outline", "dark.outline"),
    # Dividers only: subtle on purpose, so not checked.
    ("OutlineVariant", "outlineVariant", "dark.outlineVariant"),
    ("Error", "error", "error"),
    ("OnError", "fixed-white", "dark.surface"),
    ("Success", "success", "success"),
]


def hex_rgb(value):
    value = value.lstrip("#")
    if len(value) != 6:
        raise ValueError("invalid hex colour: #" + value)
    return tuple(int(value[i:i + 2], 16) / 255.0 for i in (0, 2, 4))


def relative_luminance(value):
    rgb = hex_rgb(value)

    def linear(channel):
        return channel / 12.92 if channel <= 0.04045 else ((channel + 0.055) / 1.055) ** 2.4

    r, g, b = (linear(channel) for channel in rgb)
    return 0.2126 * r + 0.7152 * g + 0.0722 * b


def contrast_ratio(first, second):
    lighter = max(relative_luminance(first), relative_luminance(second))
    darker = min(relative_luminance(first), relative_luminance(second))
    return (lighter + 0.05) / (darker + 0.05)


def resolve(data, theme, token):
    if token == "fixed-white":
        return "#FFFFFF"
    if token.startswith("dark."):
        key = token.split(".", 1)[1]
        dark = data["dark"]
        if key in dark:
            return dark[key]
        return data["light"][key]
    if theme == "dark" and token in data["dark"]:
        return data["dark"][token]
    if theme == "light" or token not in data["light"]:
        return data["light"].get(token) or data["dark"].get(token)
    return data["light"][token]


def mapped_colours(data):
    result = {}
    for theme in ("light", "dark"):
        values = {}
        for role, light_token, dark_token in ROLES:
            token = light_token if theme == "light" else dark_token
            values[role] = resolve(data, theme, token)
        result[theme] = values
    return result


def check_contrast(data):
    mapped = mapped_colours(data)
    failures = []
    # Every text/background pair the apps draw (M6-01): text on the page and
    # on its tinted containers, coloured text (links, errors, success notes),
    # and text on filled colours.
    pairs = [
        ("OnPrimary", "Primary"),
        ("OnPrimaryContainer", "PrimaryContainer"),
        ("OnError", "Error"),
    ] + [
        (foreground, background)
        for background in ("Surface", "SurfaceDim", "SurfaceHigh")
        for foreground in ("Ink", "InkMuted", "Primary", "Error", "Success")
    ]
    for theme in ("light", "dark"):
        values = mapped[theme]
        for foreground, background in pairs:
            foreground_hex = values[foreground]
            background_hex = values[background]
            ratio = contrast_ratio(foreground_hex, background_hex)
            if ratio < 4.5:
                failures.append(
                    f"{theme}: {foreground}/{background}={ratio:.2f}:1 "
                    f"(required 4.5:1, {foreground_hex} on {background_hex})"
                )
        # Non-text contrast (WCAG 2.2 SC 1.4.11, #395): the outline that draws an off
        # switch, an outlined field or button must show against the page and its containers.
        for background in NON_TEXT_BACKGROUNDS:
            outline_hex = values["Outline"]
            background_hex = values[background]
            ratio = contrast_ratio(outline_hex, background_hex)
            if ratio < 3.0:
                failures.append(
                    f"{theme}: Outline/{background}={ratio:.2f}:1 "
                    f"(required 3:1 for non-text, {outline_hex} on {background_hex})"
                )
    return failures


# What `outline` is drawn on: background and surface (Surface), surfaceContainer
# (SurfaceDim) and surfaceContainerHigh (SurfaceHigh).
NON_TEXT_BACKGROUNDS = ("Surface", "SurfaceDim", "SurfaceHigh")


def kotlin_hex(value):
    rgb = value.lstrip("#").upper()
    return "0xFF" + rgb


def android_source(mapped):
    light = mapped["light"]
    dark = mapped["dark"]
    lines = [
        HEADER.rstrip(),
        "package app.mailcrane.ui.theme",
        "",
        "import androidx.compose.material3.darkColorScheme",
        "import androidx.compose.material3.lightColorScheme",
        "import androidx.compose.ui.graphics.Color",
        "",
    ]
    lines.extend([
        "data class MailcraneExtendedColors(",
        "    val success: Color,",
        ")",
        "",
        "val MailcraneLightExtendedColors =",
        "    MailcraneExtendedColors(",
        f"        success = Color({kotlin_hex(light['Success'])}),",
        "    )",
        "",
        "val MailcraneDarkExtendedColors =",
        "    MailcraneExtendedColors(",
        f"        success = Color({kotlin_hex(dark['Success'])}),",
        "    )",
        "",
    ])

    role_arguments = [
        ("primary", "Primary"),
        ("onPrimary", "OnPrimary"),
        ("primaryContainer", "PrimaryContainer"),
        ("onPrimaryContainer", "OnPrimaryContainer"),
        ("background", "Surface"),
        ("onBackground", "Ink"),
        ("surface", "Surface"),
        ("onSurface", "Ink"),
        ("surfaceContainer", "SurfaceDim"),
        ("surfaceContainerHigh", "SurfaceHigh"),
        ("surfaceContainerLow", "SurfaceDim"),
        ("surfaceContainerHighest", "SurfaceHighest"),
        ("onSurfaceVariant", "InkMuted"),
        ("outline", "Outline"),
        ("outlineVariant", "OutlineVariant"),
        ("error", "Error"),
        ("onError", "OnError"),
    ]
    for name, values in (("Light", light), ("Dark", dark)):
        scheme = "light" if name == "Light" else "dark"
        lines.append(f"val Mailcrane{name}Colors =")
        lines.append(f"    {scheme}ColorScheme(")
        for role, brand_role in role_arguments:
            lines.append(f"        {role} = Color({kotlin_hex(values[brand_role])}),")
        lines.extend(["    )", ""])
    return "\n".join(lines)


def expected_outputs(data):
    mapped = mapped_colours(data)
    return {ANDROID_PATH: android_source(mapped)}


def write_outputs(outputs):
    for path, content in outputs.items():
        path.parent.mkdir(parents=True, exist_ok=True)
        path.write_text(content, encoding="utf-8", newline="\n")


def stale_outputs(outputs):
    stale = []
    for path, expected in outputs.items():
        if not path.is_file() or path.read_text(encoding="utf-8") != expected:
            stale.append(path.relative_to(ROOT).as_posix())
    return stale


def main():
    parser = argparse.ArgumentParser()
    parser.add_argument("--check", action="store_true", help="exit 1 if generated files are stale")
    args = parser.parse_args()

    try:
        data = json.loads(COLORS_PATH.read_text(encoding="utf-8"))
        failures = check_contrast(data)
    except (json.JSONDecodeError, KeyError, OSError, ValueError) as error:
        print(f"design colors error: {error}", file=sys.stderr)
        return 1
    if failures:
        print("contrast check failed:", file=sys.stderr)
        for failure in failures:
            print("  " + failure, file=sys.stderr)
        return 1

    outputs = expected_outputs(data)
    if args.check:
        stale = stale_outputs(outputs)
        if stale:
            print("generated theme is out of date:", file=sys.stderr)
            for path in stale:
                print("  " + path, file=sys.stderr)
            return 1
        print("generated theme is up to date")
        return 0

    write_outputs(outputs)
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
